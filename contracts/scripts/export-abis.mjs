// Exports ABIs from Foundry artifacts so the relayer, indexer, automation and web app never hand-copy them.
// Writes: contracts/abi/<Name>.json, contracts/ts/abi.ts (typed `as const` for viem), and indexer/abis/ (the
// indexer is built standalone by Envio Cloud, so it carries its own copy).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACTS = ["Circle", "CircleFactory", "CreditRegistry", "TurnAccount", "TurnKeeper", "MockAUSD"];

const INDEXED = ["Circle", "CircleFactory", "CreditRegistry", "TurnAccount"];
const indexerAbis = join(root, "..", "indexer", "abis");

mkdirSync(join(root, "abi"), { recursive: true });
mkdirSync(join(root, "ts"), { recursive: true });
mkdirSync(indexerAbis, { recursive: true });

let ts = "// Generated by contracts/scripts/export-abis.mjs — do not edit.\n\n";
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  writeFileSync(join(root, "abi", `${name}.json`), JSON.stringify(artifact.abi, null, 2) + "\n");
  if (INDEXED.includes(name)) {
    writeFileSync(join(indexerAbis, `${name}.json`), JSON.stringify(artifact.abi, null, 2) + "\n");
  }
  const id = name[0].toLowerCase() + name.slice(1);
  ts += `export const ${id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "ts", "abi.ts"), ts);
console.log(`exported ${CONTRACTS.length} ABIs`);
